package com.winteriscoming.vpn.data

import android.content.Context
import android.content.SharedPreferences
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import androidx.security.crypto.EncryptedSharedPreferences
import androidx.security.crypto.MasterKey
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Where the client private key lives.
 *
 * AndroidKeyStore has **no X25519 support**, so the scalar cannot be "kept in the
 * keystore". What we can do is keep the *right to decrypt it* in the keystore: the
 * scalar is generated by the WireGuard library, encrypted with a keystore-held
 * AES-256-GCM key, and only the ciphertext is ever written to disk.
 *
 * Deliberate trade-off: `setUserAuthenticationRequired(false)`. Requiring biometrics
 * per use would break reconnect-after-reboot and Always-on VPN, which is the whole
 * point of a VPN app. The practical consequence is that any code running as this app
 * (same UID) can obtain the key — the standard model for VPN clients, documented so
 * nobody assumes stronger isolation than exists.
 */
interface SecretStore {
    fun storePrivateKey(base64: String)
    fun loadPrivateKey(): String?
    fun clear()
}

interface SessionStore {
    var accessToken: String?
    var deviceId: String?
    var peerId: String?

    /**
     * The device public key, in hex. Not a secret (the server has it), but it must be
     * remembered: it is needed to re-upload the key after a server-side reset, and it
     * cannot be re-derived without the tunnel library.
     */
    var publicKeyHex: String?
    fun clear()
}

/** Keystore-wrapped key material + EncryptedSharedPreferences for the ciphertext. */
class KeystoreSecretStore(context: Context) : SecretStore {

    private val prefs: SharedPreferences = EncryptedSharedPreferences.create(
        context,
        "vpn-secrets",
        MasterKey.Builder(context).setKeyScheme(MasterKey.KeyScheme.AES256_GCM).build(),
        EncryptedSharedPreferences.PrefKeyEncryptionScheme.AES256_SIV,
        EncryptedSharedPreferences.PrefValueEncryptionScheme.AES256_GCM,
    )

    override fun storePrivateKey(base64: String) {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, masterKey())
        val iv = cipher.iv
        val encrypted = cipher.doFinal(base64.toByteArray(Charsets.US_ASCII))
        // iv and ciphertext together; the GCM tag is appended to the ciphertext.
        val payload = ByteArray(iv.size + encrypted.size)
        System.arraycopy(iv, 0, payload, 0, iv.size)
        System.arraycopy(encrypted, 0, payload, iv.size, encrypted.size)
        prefs.edit().putString(KEY_WRAPPED, Base64.encodeToString(payload, Base64.NO_WRAP)).apply()
    }

    override fun loadPrivateKey(): String? {
        val stored = prefs.getString(KEY_WRAPPED, null) ?: return null
        val payload = Base64.decode(stored, Base64.NO_WRAP)
        if (payload.size <= IV_BYTES) return null
        return runCatching {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(
                Cipher.DECRYPT_MODE,
                masterKey(),
                GCMParameterSpec(TAG_BITS, payload, 0, IV_BYTES),
            )
            String(cipher.doFinal(payload, IV_BYTES, payload.size - IV_BYTES), Charsets.US_ASCII)
        }.getOrNull() // a re-keyed or factory-reset keystore yields null: re-onboard
    }

    override fun clear() {
        prefs.edit().remove(KEY_WRAPPED).apply()
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        if (keyStore.containsAlias(ALIAS)) keyStore.deleteEntry(ALIAS)
    }

    private fun masterKey(): SecretKey {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        (keyStore.getEntry(ALIAS, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        val builder = KeyGenParameterSpec.Builder(
            ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setUserAuthenticationRequired(false)
        generator.init(builder.build())
        return generator.generateKey()
    }

    private companion object {
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val ALIAS = "vpn-tunnel-key-wrapper"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val IV_BYTES = 12
        const val TAG_BITS = 128
        const val KEY_WRAPPED = "peer_private_key_wrapped"
    }
}

/** Token and identity: EncryptedSharedPreferences, never plain SharedPreferences. */
class PrefsSessionStore(context: Context) : SessionStore {

    private val prefs: SharedPreferences = EncryptedSharedPreferences.create(
        context,
        "vpn-session",
        MasterKey.Builder(context).setKeyScheme(MasterKey.KeyScheme.AES256_GCM).build(),
        EncryptedSharedPreferences.PrefKeyEncryptionScheme.AES256_SIV,
        EncryptedSharedPreferences.PrefValueEncryptionScheme.AES256_GCM,
    )

    override var accessToken: String?
        get() = prefs.getString("access_token", null)
        set(value) = prefs.edit().putString("access_token", value).apply()

    override var deviceId: String?
        get() = prefs.getString("device_id", null)
        set(value) = prefs.edit().putString("device_id", value).apply()

    override var peerId: String?
        get() = prefs.getString("peer_id", null)
        set(value) = prefs.edit().putString("peer_id", value).apply()

    override var publicKeyHex: String?
        get() = prefs.getString("public_key_hex", null)
        set(value) = prefs.edit().putString("public_key_hex", value).apply()

    override fun clear() {
        prefs.edit().clear().apply()
    }
}
